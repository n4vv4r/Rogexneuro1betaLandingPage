import crypto from "node:crypto";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const lab = process.env.ECHOAI_LAB_DIR
  ? path.resolve(process.env.ECHOAI_LAB_DIR)
  : path.resolve(root, "..", "lab");
let tracePath = process.env.ECHOAI_TRACE
  ? path.resolve(process.env.ECHOAI_TRACE)
  : path.join(os.tmpdir(), "echo1-benchmark-trace.jsonl");

const reportNames = [
  "nexus0_report.json",
  "nexus0_pattern0_report.json",
  "nexus0_xfer1_report.json",
  "nexus0_signc_report.json",
  "nexus0_talk1_report.json",
  "nexus0_room1_report.json",
  "nexus0_obj1_report.json",
  "nexus0_open1_report.json",
];

const read = (name) => JSON.parse(fs.readFileSync(path.join(lab, name), "utf8"));
const sha256 = (file) => crypto
  .createHash("sha256")
  .update(fs.readFileSync(file))
  .digest("hex");

const [core, pattern, xfer, sign, talk, room, object, open] = reportNames.map(read);

if (!process.env.ECHOAI_TRACE) {
  const echoaiRoot = path.dirname(lab);
  const packageRoot = path.dirname(echoaiRoot);
  if (!fs.existsSync(path.join(echoaiRoot, "nexus0", "bench.py"))) {
    throw new Error("echoAI source not found; set ECHOAI_LAB_DIR and ECHOAI_TRACE explicitly");
  }
  fs.rmSync(tracePath, { force: true });
  const pythonPath = [packageRoot, process.env.PYTHONPATH].filter(Boolean).join(path.delimiter);
  const result = spawnSync("python3", [
    "-c",
    `from echoai.nexus0.bench import run; run(thought_log=${JSON.stringify(tracePath)})`,
  ], {
    cwd: packageRoot,
    env: { ...process.env, PYTHONPATH: pythonPath },
    encoding: "utf8",
  });
  if (result.status !== 0) {
    throw new Error(`canonical trace failed: ${result.stderr || result.stdout}`);
  }
}

const trace = fs.readFileSync(tracePath, "utf8")
  .trim()
  .split("\n")
  .filter(Boolean)
  .map((line) => JSON.parse(line));

if (trace.length !== core.turns) {
  throw new Error(`trace has ${trace.length} rows; canonical report has ${core.turns} turns`);
}
if (!core.negative_delta_causes_policy_change
    || core.false_facts !== 0
    || core.destroyed !== 0
    || core.cortex_calls !== 0) {
  throw new Error("canonical NEXUS-0 locks are not green");
}
for (const [name, report] of [
  ["PATTERN-0", pattern], ["XFER-1", xfer], ["SIGN-C", sign],
  ["TALK-1", talk], ["ROOM-1", room], ["OBJ-1", object], ["OPEN-1", open],
]) {
  if (report.green !== true) throw new Error(`${name} report is not green`);
}

const sources = reportNames.map((name) => ({
  file: `echoai/lab/${name}`,
  sha256: sha256(path.join(lab, name)),
}));
sources.push({
  file: "canonical trace generated by bench.run(thought_log=...)",
  sha256: sha256(tracePath),
});

